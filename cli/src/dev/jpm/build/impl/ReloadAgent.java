package dev.jpm.build.impl;

public final class ReloadAgent {
    private ReloadAgent() {}

    public static final String CLASS = "dev.jpm.reload.Agent";

    public static final String SOURCE = """
            package dev.jpm.reload;

            import java.io.IOException;
            import java.lang.instrument.ClassDefinition;
            import java.lang.instrument.Instrumentation;
            import java.nio.charset.StandardCharsets;
            import java.nio.file.Files;
            import java.nio.file.Path;
            import java.nio.file.Paths;
            import java.nio.file.StandardCopyOption;
            import java.util.ArrayList;
            import java.util.HashMap;
            import java.util.List;
            import java.util.Map;

            /**
             * Generated by jpm for `jpm dev`. Redefines classes in this JVM when jpm asks: jpm writes "request" (one
             * "name<TAB>class file" per line) into the folder given as the agent's argument, and this answers with
             * "result": "ok <count>" or "fail <reason>".
             */
            public final class Agent {
                private Agent() {}

                public static void premain(String arg, final Instrumentation inst) {
                    final Path dir = Paths.get(arg);
                    Thread t = new Thread(new Runnable() {
                        public void run() {
                            loop(dir, inst);
                        }
                    }, "jpm-reload");
                    t.setDaemon(true);
                    t.start();
                }

                private static void loop(Path dir, Instrumentation inst) {
                    Path request = dir.resolve("request");
                    while (true) {
                        try {
                            if (Files.exists(request)) {
                                String answer = handle(new String(Files.readAllBytes(request), StandardCharsets.UTF_8), inst);
                                Files.delete(request);
                                Path tmp = dir.resolve("result.tmp");
                                Files.write(tmp, answer.getBytes(StandardCharsets.UTF_8));
                                Files.move(tmp, dir.resolve("result"), StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
                            }
                            Thread.sleep(100);
                        } catch (InterruptedException e) {
                            return;
                        } catch (IOException e) {
                            try {
                                Thread.sleep(500);
                            } catch (InterruptedException ie) {
                                return;
                            }
                        }
                    }
                }

                private static String handle(String text, Instrumentation inst) {
                    Map<String, Path> files = new HashMap<String, Path>();
                    for (String line : text.split("\\n")) {
                        int tab = line.indexOf('\\t');
                        if (tab > 0) files.put(line.substring(0, tab), Paths.get(line.substring(tab + 1).trim()));
                    }
                    List<ClassDefinition> defs = new ArrayList<ClassDefinition>();
                    try {
                        for (Class<?> c : inst.getAllLoadedClasses()) {
                            Path f = files.get(c.getName());
                            if (f != null && inst.isModifiableClass(c)) defs.add(new ClassDefinition(c, Files.readAllBytes(f)));
                        }
                        if (!defs.isEmpty()) inst.redefineClasses(defs.toArray(new ClassDefinition[0]));
                        return "ok " + defs.size();
                    } catch (Throwable e) {
                        String msg = e.getMessage();
                        return "fail " + e.getClass().getSimpleName() + (msg == null ? "" : ": " + msg.replace('\\n', ' '));
                    }
                }
            }
            """;
}
