package dev.jpm.build;

/**
 * Source of the launcher and class loaders that jpm compiles into every bundle. Java 8 compatible, no
 * dependencies. Kept as text so that it is compiled for the bundle's target release.
 */
final class BundleLauncher {
    private BundleLauncher() {}

    static final String PACKAGE = "dev.jpm.bundle";

    static final String LAUNCHER = """
            package dev.jpm.bundle;

            import java.io.InputStream;
            import java.lang.reflect.Method;
            import java.net.URL;
            import java.net.URLClassLoader;
            import java.nio.file.Files;
            import java.nio.file.Path;
            import java.nio.file.Paths;
            import java.nio.file.StandardCopyOption;
            import java.util.ArrayList;
            import java.util.Arrays;
            import java.util.Enumeration;
            import java.util.HashSet;
            import java.util.List;
            import java.util.Properties;
            import java.util.Set;
            import java.util.jar.JarEntry;
            import java.util.jar.JarFile;

            /**
             * Generated by jpm. Starts a bundle: unpacks the nested jars once into a cache directory, builds the
             * shared class loader and one isolated loader per implementation module, then runs the main class.
             */
            public final class Launcher {
                private Launcher() {}

                public static void main(String[] args) throws Throwable {
                    Properties p = new Properties();
                    try (InputStream in = Launcher.class.getResourceAsStream("/META-INF/jpm/bundle.properties")) {
                        if (in == null) throw new IllegalStateException("not a jpm bundle: META-INF/jpm/bundle.properties is missing");
                        p.load(in);
                    }
                    Path self = Paths.get(Launcher.class.getProtectionDomain().getCodeSource().getLocation().toURI());
                    Path dir = unpack(self, p.getProperty("id"));

                    ClassLoader jdk = Launcher.class.getClassLoader().getParent();
                    URLClassLoader shared = new URLClassLoader(urls(dir, p.getProperty("shared", "")), jdk);
                    List<IsolatedLoader> isolated = new ArrayList<IsolatedLoader>();
                    for (String name : split(p.getProperty("isolated", ""))) {
                        Set<String> api = new HashSet<String>(split(p.getProperty("isolated." + name + ".api", "")));
                        isolated.add(new IsolatedLoader(name, urls(dir, p.getProperty("isolated." + name + ".jars", "")), shared, api));
                    }
                    // Registries that find implementations by name (ServiceLoader, Class.forName with the context
                    // loader) see the isolated modules through the context class loader.
                    ClassLoader context = isolated.isEmpty() ? shared : new ContextLoader(shared, isolated);
                    Thread.currentThread().setContextClassLoader(context);

                    Class<?> main = Class.forName(p.getProperty("main"), false, shared);
                    Method m = main.getMethod("main", String[].class);
                    try {
                        m.invoke(null, (Object) args);
                    } catch (java.lang.reflect.InvocationTargetException e) {
                        throw e.getCause();
                    }
                }

                static List<String> split(String s) {
                    List<String> out = new ArrayList<String>();
                    for (String x : s.split(",")) if (!x.trim().isEmpty()) out.add(x.trim());
                    return out;
                }

                private static URL[] urls(Path dir, String list) throws Exception {
                    List<String> names = split(list);
                    URL[] out = new URL[names.size()];
                    for (int i = 0; i < out.length; i++) out[i] = dir.resolve(names.get(i)).toUri().toURL();
                    return out;
                }

                /** Unpacks META-INF/jpm/lib/ into a directory named after the bundle's content id, once. */
                private static Path unpack(Path self, String id) throws Exception {
                    String base = System.getenv("JPM_BUNDLE_CACHE");
                    Path root = base != null && !base.isEmpty() ? Paths.get(base)
                            : Paths.get(System.getProperty("java.io.tmpdir"), "jpm-bundles-" + System.getProperty("user.name", "user"));
                    Path dir = root.resolve(id);
                    if (Files.exists(dir.resolve(".complete"))) return dir;
                    Files.createDirectories(root);
                    Path tmp = Files.createTempDirectory(root, id + ".tmp");
                    try (JarFile jar = new JarFile(self.toFile())) {
                        Enumeration<JarEntry> en = jar.entries();
                        while (en.hasMoreElements()) {
                            JarEntry e = en.nextElement();
                            String n = e.getName();
                            if (!n.startsWith("META-INF/jpm/lib/") || e.isDirectory() || n.contains("..")) continue;
                            Path target = tmp.resolve(n.substring("META-INF/jpm/".length()));
                            Files.createDirectories(target.getParent());
                            try (InputStream in = jar.getInputStream(e)) {
                                Files.copy(in, target, StandardCopyOption.REPLACE_EXISTING);
                            }
                        }
                    }
                    Files.createFile(tmp.resolve(".complete"));
                    try {
                        Files.move(tmp, dir, StandardCopyOption.ATOMIC_MOVE);
                    } catch (java.io.IOException raced) {
                        // another process unpacked it first
                        if (!Files.exists(dir.resolve(".complete"))) throw raced;
                    }
                    return dir;
                }

                static String packageOf(String className) {
                    int dot = className.lastIndexOf('.');
                    return dot < 0 ? "" : className.substring(0, dot);
                }

                static boolean jdkClass(String name) {
                    return name.startsWith("java.") || name.startsWith("javax.") || name.startsWith("jdk.")
                            || name.startsWith("sun.") || name.startsWith("com.sun.") || name.startsWith("org.w3c.")
                            || name.startsWith("org.xml.") || name.startsWith("org.ietf.");
                }
            }

            /**
             * Loads an implementation module child-first: its own jars before the shared loader, except for the JDK
             * and the packages of the API it implements, which always come from the shared loader.
             */
            final class IsolatedLoader extends URLClassLoader {
                static { ClassLoader.registerAsParallelCapable(); }

                private final String name;
                private final Set<String> api;

                IsolatedLoader(String name, URL[] urls, ClassLoader parent, Set<String> api) {
                    super(urls, parent);
                    this.name = name;
                    this.api = api;
                }

                private boolean parentFirst(String className) {
                    return Launcher.jdkClass(className) || api.contains(Launcher.packageOf(className));
                }

                @Override
                protected Class<?> loadClass(String className, boolean resolve) throws ClassNotFoundException {
                    synchronized (getClassLoadingLock(className)) {
                        Class<?> c = findLoadedClass(className);
                        if (c == null) {
                            if (parentFirst(className)) {
                                return super.loadClass(className, resolve);
                            }
                            try {
                                c = findClass(className);
                            } catch (ClassNotFoundException e) {
                                return super.loadClass(className, resolve);
                            }
                        }
                        if (resolve) resolveClass(c);
                        return c;
                    }
                }

                @Override
                public URL getResource(String resource) {
                    String asClass = resource.endsWith(".class") ? resource.substring(0, resource.length() - 6).replace('/', '.') : null;
                    if (asClass == null || !parentFirst(asClass)) {
                        URL own = findResource(resource);
                        if (own != null) return own;
                    }
                    return super.getResource(resource);
                }

                @Override
                public String toString() {
                    return "jpm isolated loader for " + name;
                }
            }

            /** Context class loader: the shared loader first, then every isolated module. */
            final class ContextLoader extends ClassLoader {
                static { ClassLoader.registerAsParallelCapable(); }

                private final List<IsolatedLoader> isolated;

                ContextLoader(ClassLoader shared, List<IsolatedLoader> isolated) {
                    super(shared);
                    this.isolated = isolated;
                }

                @Override
                protected Class<?> findClass(String name) throws ClassNotFoundException {
                    for (IsolatedLoader l : isolated) {
                        try {
                            return l.loadClass(name);
                        } catch (ClassNotFoundException ignored) {
                        }
                    }
                    throw new ClassNotFoundException(name);
                }

                @Override
                protected URL findResource(String name) {
                    for (IsolatedLoader l : isolated) {
                        URL u = l.findResource(name);
                        if (u != null) return u;
                    }
                    return null;
                }

                @Override
                protected Enumeration<URL> findResources(String name) throws java.io.IOException {
                    List<URL> all = new ArrayList<URL>();
                    for (IsolatedLoader l : isolated) {
                        Enumeration<URL> e = l.findResources(name);
                        while (e.hasMoreElements()) all.add(e.nextElement());
                    }
                    return java.util.Collections.enumeration(all);
                }

                @Override
                public String toString() {
                    return "jpm context loader " + Arrays.toString(isolated.toArray());
                }
            }
            """;
}
