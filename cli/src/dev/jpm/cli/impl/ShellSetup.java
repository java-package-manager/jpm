package dev.jpm.cli.impl;

import dev.jpm.log.Log;
import dev.jpm.util.Fs;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;

final class ShellSetup {
    private ShellSetup() {
    }

    static final String MARKER = "# Added by the jpm installer";

    static boolean windows() {
        return System.getProperty("os.name").toLowerCase().contains("win");
    }

    static Path envFile() {
        return Fs.home().resolve("env");
    }

    static String shownBin() {
        Path bin = Shims.bin().toAbsolutePath().normalize();
        String home = System.getenv("HOME");
        if (home != null && !home.isBlank()) {
            Path h = Path.of(home).toAbsolutePath().normalize();
            if (bin.startsWith(h)) return "$HOME/" + h.relativize(bin).toString().replace('\\', '/');
        }
        return bin.toString();
    }

    static String posixEnv() {
        return """
                # Generated by jpm (`jvm setup`); sourced from your shell's startup file. Do not edit: it is rewritten.
                # Keeps %1$s first on PATH so its java, javac, ... shims are found before any other JDK.
                __jpm_path() {
                  __jpm_bin="%1$s"
                  __jpm_rest=":${PATH:-}:"
                  while :; do
                    case "$__jpm_rest" in
                      *":$__jpm_bin:"*) __jpm_rest="${__jpm_rest%%%%:$__jpm_bin:*}:${__jpm_rest#*:$__jpm_bin:}" ;;
                      *) break ;;
                    esac
                  done
                  __jpm_rest="${__jpm_rest#:}"
                  __jpm_rest="${__jpm_rest%%:}"
                  case "${PATH:-}" in
                    "$__jpm_bin" | "$__jpm_bin":*) ;;
                    *) PATH="$__jpm_bin${__jpm_rest:+:$__jpm_rest}"; export PATH ;;
                  esac
                  unset __jpm_bin __jpm_rest
                }
                __jpm_path
                # Something may put another JDK first later on; move jpm back to the front before each prompt.
                if [ -n "${ZSH_VERSION:-}" ]; then
                  autoload -Uz add-zsh-hook 2>/dev/null && add-zsh-hook precmd __jpm_path
                elif [ -n "${BASH_VERSION:-}" ]; then
                  case ";${PROMPT_COMMAND:-};" in
                    *";__jpm_path;"*) ;;
                    *) PROMPT_COMMAND="__jpm_path${PROMPT_COMMAND:+;$PROMPT_COMMAND}" ;;
                  esac
                fi
                """.formatted(shownBin());
    }

    static String fishConf() {
        String bin = Shims.bin().toAbsolutePath().normalize().toString();
        return """
                # Generated by jpm (`jvm setup`). Do not edit: it is rewritten.
                # Keeps %1$s first on PATH so its java, javac, ... shims are found before any other JDK.
                fish_add_path --global --move --path "%1$s"
                function __jpm_path --on-event fish_prompt
                    fish_add_path --global --move --path "%1$s"
                end
                """.formatted(bin);
    }

    static String sourceLine() {
        String env = envFile().toAbsolutePath().normalize().toString();
        String home = System.getenv("HOME");
        if (home != null && env.startsWith(Path.of(home).toAbsolutePath().normalize().toString())) {
            env = "$HOME" + env.substring(Path.of(home).toAbsolutePath().normalize().toString().length());
        }
        return "[ -f \"" + env + "\" ] && . \"" + env + "\"";
    }

    private static Path home() {
        String h = System.getenv("HOME");
        return Path.of(h != null && !h.isBlank() ? h : System.getProperty("user.home"));
    }

    static List<Path> rcFiles() {
        Path home = home();
        String shell = System.getenv("SHELL");
        String name = shell == null ? "sh" : Path.of(shell).getFileName().toString();
        boolean mac = System.getProperty("os.name").toLowerCase().contains("mac");
        List<Path> out = new ArrayList<>();
        switch (name) {
            case "zsh" -> {
                String zdot = System.getenv("ZDOTDIR");
                out.add((zdot != null && !zdot.isBlank() ? Path.of(zdot) : home).resolve(".zshrc"));
            }
            case "bash" -> {
                out.add(home.resolve(".bashrc"));
                if (mac || Files.exists(home.resolve(".bash_profile"))) out.add(home.resolve(".bash_profile"));
            }
            case "fish" -> out.add(fishFile());
            default -> out.add(home.resolve(".profile"));
        }
        return out;
    }

    static Path fishFile() {
        String xdg = System.getenv("XDG_CONFIG_HOME");
        Path base = xdg != null && !xdg.isBlank() ? Path.of(xdg) : home().resolve(".config");
        return base.resolve("fish").resolve("conf.d").resolve("jpm.fish");
    }

    private static Set<Path> knownRcFiles() {
        Path home = home();
        Set<Path> all = new LinkedHashSet<>();
        String zdot = System.getenv("ZDOTDIR");
        all.add((zdot != null && !zdot.isBlank() ? Path.of(zdot) : home).resolve(".zshrc"));
        all.add(home.resolve(".bashrc"));
        all.add(home.resolve(".bash_profile"));
        all.add(home.resolve(".profile"));
        return all;
    }

    static List<Path> setup() {
        List<Path> changed = new ArrayList<>();
        if (windows()) return changed;
        Fs.writeIfChanged(envFile(), posixEnv());
        Set<Path> targets = new LinkedHashSet<>(rcFiles());
        for (Path f : knownRcFiles()) if (Files.isRegularFile(f) && hasOldLine(Fs.read(f))) targets.add(f);
        for (Path f : targets) {
            if (f.equals(fishFile())) {
                if (Fs.writeIfChanged(f, fishConf())) changed.add(f);
                continue;
            }
            String src = Files.isRegularFile(f) ? Fs.read(f) : "";
            String next = withSourceLine(src);
            if (!next.equals(src)) {
                Fs.write(f, next);
                changed.add(f);
            }
        }
        return changed;
    }

    static boolean hasOldLine(String rc) {
        return oldLineIndex(rc.split("\n", -1)) >= 0;
    }

    private static int oldLineIndex(String[] lines) {
        for (int i = 0; i + 1 < lines.length; i++) {
            if (lines[i].trim().equals(MARKER) && lines[i + 1].contains(".jpm/bin") && lines[i + 1].contains("PATH")) return i + 1;
        }
        return -1;
    }

    static boolean sourcesEnv(String rc) {
        String abs = envFile().toAbsolutePath().normalize().toString();
        return rc.contains(abs) || rc.contains(sourceLine());
    }

    static String withSourceLine(String rc) {
        String line = sourceLine();
        if (sourcesEnv(rc)) return rc;
        String[] lines = rc.split("\n", -1);
        int old = oldLineIndex(lines);
        if (old >= 0) {
            lines[old] = line;
            return String.join("\n", lines);
        }
        StringBuilder sb = new StringBuilder(rc);
        if (!rc.isEmpty() && !rc.endsWith("\n")) sb.append('\n');
        if (!rc.isEmpty()) sb.append('\n');
        sb.append(MARKER).append('\n').append(line).append('\n');
        return sb.toString();
    }

    static boolean configured() {
        if (windows()) return true;
        for (Path f : rcFiles()) {
            if (!Files.isRegularFile(f)) return false;
            String s = Fs.read(f);
            if (f.equals(fishFile()) ? !s.contains("fish_add_path") : !sourcesEnv(s)) return false;
        }
        return true;
    }

    static void ensure(boolean quiet) {
        if (System.getenv("JPM_NO_MODIFY_PATH") != null) return;
        List<Path> changed = setup();
        if (!quiet) {
            for (Path f : changed) Log.step("Shell", "keeps " + shownBin() + " first on PATH, via " + f);
        }
    }
}
